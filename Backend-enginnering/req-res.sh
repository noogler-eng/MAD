# pre flight Request
# dont have req and resp body
# this method is not GET, POST, HEAD, so browser will send a preflight request to the server to check if the actual request is safe to send.
# includes non simple headers like Content-Type, Authorization, etc.
# inquiring about the server's CORS policy before sending the actual request.
# also about the allowed methods and headers for the actual request.
OPTIONS /api/products/123 HTTP/1.1
Host: api.anotherdomain.com
Origin: https://example.com
Access-Control-Request-Method: PUT
Access-Control-Request-Headers: Content-Type, Authorization


# Respnse to preflight request
HTTP/1.1 204 No Content
Access-Control-Allow-Origin: https://example.com
Access-Control-Allow-Methods: PUT, DELETE
Access-Control-Allow-Headers: Authorization
Access-Control-Max-Age: 86400


