# CORS (cross-origin resource sharing)
# It allows sever to specify who can access its resources and how they can be accessed. 
# It is a security feature implemented by web browsers to prevent malicious websites from 
# making unauthorized requests to a different domain.


# simple Request
"example.com" -> "api.example.com"
GET /api/products/123 HTTP/1.1
# different Host and Origin headers
Host: api.anotherdomain.com
Origin: https://example.com
Accept: application/json

# server response
HTTP/1.1 200 OK
Content-Type: application/json
# server checks this wheather exists allowed origin in its configuration and 
# if it does, it will include the following header in the response
# Browser will allow the response to be accessed by the requesting origin (example.com)
# wildcard: "*", allow every origin
Access-Control-Allow-Origin: https://example.com

{
    "Product": {
