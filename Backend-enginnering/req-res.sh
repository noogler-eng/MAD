# different type of headers
# 1. User-Agent: Identifies the client software making the request (e.g., browser, mobile app).
# 2. Content-Type: Specifies the media type of the request body (e.g., application/json, text/html).
# 3. Authorization: Contains credentials for authenticating the client with the server (e.g., Bearer token, Basic auth).
# 4. Accept: Indicates the media types that the client can process in the response (e.g., application/json, text/html).
# 5. Cookie: Sends stored cookies from the client to the server for session management or personalization.
# 6. Cache-Control: Directs caching behavior for the request or response (e.g., no-cache, no-store, max-age).
# 7. X-Request-ID: A unique identifier for the request, often used for tracing and debugging purposes.
# 8. Strict-Transport-Security: Instructs the browser to only communicate with the server over HTTPS for a specified period of time, enhancing security.
# 9. Vary: Informs caches that the response may vary based on certain request headers (e.g., Accept-Encoding, User-Agent).
# 10. Connection: Controls whether the network connection remains open after the current transaction (e.g., keep-alive, close).
# 11. Referer: Indicates the URL of the page that made the request, often used for analytics and security purposes.
# 12. Date: Provides the date and time at which the response was generated by the server.


# Represetation Headers
# 1. Content-Length: Specifies the size of the response body in bytes, allowing the client to know how much data to expect.
# 2. Content-Type: Indicates the media type of the response body (e.g., application/json, text/html), helping the client understand how to process the data.


# security headers
# 1. Strict-Transport-Security: Enforces secure (HTTPS) connections to the server, preventing man-in-the-middle attacks
# 2. X-Content-Type-Options: Prevents browsers from interpreting files as a different MIME type, reducing the risk of drive-by downloads.'
# 3. X-Frame-Options: Protects against clickjacking attacks by controlling whether the content can be embedded in an iframe.
# 4. Content-Security-Policy: Helps prevent cross-site scripting (XSS) and other code injection attacks by specifying which sources of content are allowed.
# 5. X-XSS-Protection: Enables the cross-site scripting (XSS) filter built into most modern web browsers, providing an additional layer of protection against XSS attacks.


